/**
 * Drawing primitives for the garment kit. Every garment module builds its
 * markup from these, so the whole set shares one line, one palette and one
 * framing. `README.md` in this folder describes the visual language; the
 * short version:
 *
 *   - Design space is 200 units wide, garments centered on x = 100. Pieces are
 *     drawn as flat lays seen from the front (shoes from the side, toe right).
 *   - One line: `--icon-stroke`, 1 screen px (`vector-effect` on every stroke).
 *     Outlines at full ink, seams and stitching at `SEAM` opacity.
 *   - Paint is only the four icon variables. Depth comes from `shade()`, which
 *     lays the ink at a low opacity (darkens light pieces, lifts dark ones).
 *   - A piece is `{ base, lines, clip }`: `base` is the fabric a pattern may
 *     cover, `lines` is everything that stays above it (trims in `FILL2`,
 *     shading, ink). `piece()` frames the result in a square viewBox.
 */
import type { ArtLayers, Box, KitPiece } from "./types";

export const FILL = "var(--icon-fill, #b3b3b3)";
export const FILL2 = "var(--icon-fill-2, #8c8c8c)";
export const INK = "var(--icon-stroke, #000)";
export const PATTERN = "var(--icon-pattern, #000)";

/** Opacity of interior seams and stitching, relative to the outline ink. */
export const SEAM = 0.5;
/** Opacity of the ink used as shadow (`shade`). */
export const SHADOW = 0.1;

/** The horizontal center of the design space. */
export const CX = 100;

export type Pt = readonly [number, number];

/** Numbers are rounded to one decimal to keep the generated markup compact. */
export const num = (v: number): string => {
  const r = Math.round(v * 10) / 10;
  return String(r === 0 ? 0 : r);
};

const pt = ([x, y]: Pt) => `${num(x)} ${num(y)}`;

/* ------------------------------------------------------------------ */
/* Path data                                                            */
/* ------------------------------------------------------------------ */

/**
 * One segment of a path, as absolute coordinates. `symmetric()` and
 * `boundsOf()` only understand these three, so stick to them.
 */
export type Seg =
  | readonly ["L", Pt]
  | readonly ["Q", Pt, Pt]
  | readonly ["C", Pt, Pt, Pt];

export const L = (p: Pt): Seg => ["L", p];
export const Q = (c: Pt, p: Pt): Seg => ["Q", c, p];
export const C = (c1: Pt, c2: Pt, p: Pt): Seg => ["C", c1, c2, p];

function segToString(seg: Seg): string {
  switch (seg[0]) {
    case "L":
      return `L${pt(seg[1])}`;
    case "Q":
      return `Q${pt(seg[1])} ${pt(seg[2])}`;
    case "C":
      return `C${pt(seg[1])} ${pt(seg[2])} ${pt(seg[3])}`;
  }
}

/** Path data from a start point and segments. `close` appends Z. */
export function path(start: Pt, segs: readonly Seg[], close = false): string {
  return `M${pt(start)}${segs.map(segToString).join("")}${close ? "Z" : ""}`;
}

/** A straight open line between points. */
export function polyline(...points: Pt[]): string {
  return path(points[0], points.slice(1).map(L));
}

const mirror = ([x, y]: Pt, cx: number): Pt => [2 * cx - x, y];

/**
 * A closed shape symmetric about x = `cx`, from its right half. The half
 * starts on the axis, runs around the right side and ends on the axis again;
 * the left half is generated by mirroring the segments in reverse.
 */
export function symmetric(start: Pt, segs: readonly Seg[], cx = CX): string {
  const left: Seg[] = [];
  let from: Pt = start;
  const ends: Pt[] = [];
  for (const seg of segs) {
    ends.push(from);
    from = seg[seg.length - 1] as Pt;
  }
  for (let i = segs.length - 1; i >= 0; i--) {
    const seg = segs[i];
    const to = mirror(ends[i], cx);
    switch (seg[0]) {
      case "L":
        left.push(["L", to]);
        break;
      case "Q":
        left.push(["Q", mirror(seg[1], cx), to]);
        break;
      case "C":
        left.push(["C", mirror(seg[2], cx), mirror(seg[1], cx), to]);
        break;
    }
  }
  return path(start, [...segs, ...left], true);
}

/** The same path data mirrored about x = `cx` (for a left sleeve, pocket...). */
export function mirrored(d: string, cx = CX): string {
  return d.replace(/([MLQC])([^MLQCZ]+)/g, (_, cmd: string, nums: string) => {
    const values = nums.trim().split(/[\s,]+/).map(Number);
    const out: string[] = [];
    for (let i = 0; i < values.length; i += 2) out.push(`${num(2 * cx - values[i])} ${num(values[i + 1])}`);
    return cmd + out.join(" ");
  });
}

/** Linear interpolation between two points. */
export const lerp = (a: Pt, b: Pt, t: number): Pt => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t];

/** A point moved by a vector. */
export const add = (a: Pt, b: Pt, k = 1): Pt => [a[0] + b[0] * k, a[1] + b[1] * k];

/** Unit vector at `deg` degrees, measured from +x towards +y (downwards). */
export const dir = (deg: number): Pt => [Math.cos((deg * Math.PI) / 180), Math.sin((deg * Math.PI) / 180)];

/** The unit vector perpendicular to `v`, rotated clockwise on screen. */
export const perp = ([x, y]: Pt): Pt => [-y, x];

/* ------------------------------------------------------------------ */
/* Bounds                                                               */
/* ------------------------------------------------------------------ */

function sampleBezier(points: Pt[], t: number): Pt {
  let pts = points;
  while (pts.length > 1) {
    const next: Pt[] = [];
    for (let i = 0; i < pts.length - 1; i++) next.push(lerp(pts[i], pts[i + 1], t));
    pts = next;
  }
  return pts[0];
}

/** The bounding box of absolute path data made of M, L, Q, C and Z. */
export function boundsOf(ds: readonly string[]): Box {
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  const see = ([x, y]: Pt) => {
    if (x < minX) minX = x;
    if (x > maxX) maxX = x;
    if (y < minY) minY = y;
    if (y > maxY) maxY = y;
  };
  for (const d of ds) {
    let cur: Pt = [0, 0];
    for (const m of d.matchAll(/([MLQCZ])([^MLQCZ]*)/g)) {
      const cmd = m[1];
      const v = m[2].trim() ? m[2].trim().split(/[\s,]+/).map(Number) : [];
      if (cmd === "Z") continue;
      if (cmd === "M" || cmd === "L") {
        cur = [v[0], v[1]];
        see(cur);
        continue;
      }
      const ctrl: Pt[] = [cur];
      for (let i = 0; i < v.length; i += 2) ctrl.push([v[i], v[i + 1]]);
      for (let s = 0; s <= 12; s++) see(sampleBezier(ctrl, s / 12));
      cur = ctrl[ctrl.length - 1];
    }
  }
  return [minX, minY, maxX - minX, maxY - minY];
}

/* ------------------------------------------------------------------ */
/* Elements                                                             */
/* ------------------------------------------------------------------ */

/** A filled area (no stroke; the outline is drawn separately in `lines`). */
export const fill = (d: string, paint: string = FILL): string => `<path d="${d}" fill="${paint}"/>`;

/** Ink laid at a low opacity: shadow on light pieces, highlight on dark ones. */
export const shade = (d: string, opacity: number = SHADOW): string =>
  `<path d="${d}" fill="${INK}" fill-opacity="${num(opacity)}"/>`;

/** One stroked path; must sit inside `ink()`, which carries the paint. */
export const stroke = (d: string, opacity?: number): string =>
  `<path d="${d}"${opacity !== undefined && opacity < 1 ? ` stroke-opacity="${num(opacity)}"` : ""} vector-effect="non-scaling-stroke"/>`;

/** An interior seam or stitch line. */
export const seam = (d: string): string => stroke(d, SEAM);

/** A small round button, stud or grommet. */
export const button = (cx: number, cy: number, r: number, paint: string = FILL2): string =>
  `<circle cx="${num(cx)}" cy="${num(cy)}" r="${num(r)}" fill="${paint}" stroke="${INK}" stroke-width="1" vector-effect="non-scaling-stroke"/>`;

/** The ink group every piece's strokes live in. One line weight for the whole kit. */
export const ink = (...items: string[]): string =>
  `<g fill="none" stroke="${INK}" stroke-width="1" stroke-linecap="round" stroke-linejoin="round">${items.join("")}</g>`;

